test('catalog supports search, combined filters, URL state, and NFT detail deep links', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Emerald Ape #042', { exact: true })).toBeVisible()
  await page.getByText('Busca e filtros').click()
  await page.getByLabel('Buscar NFTs').fill('Golden')
  await page.getByLabel('Rede', { exact: true }).selectOption('Polygon')
  await expect(page.getByText('Golden Beat #207')).toBeVisible()
  await expect(page.getByText('Golden Signal #160')).not.toBeVisible()
  await expect(page).toHaveURL(/q=Golden/)
  await page.getByText('Golden Beat #207').click()
  await expect(page).toHaveURL(/\/mercado\/207$/)
  await expect(page.getByRole('heading', { name: 'Golden Beat #207', level: 1 })).toBeVisible()
})

