test('socket reconnects after the mock server closes the first connection', async ({ page }) => {
  const socketConnections: string[] = []
  page.on('websocket', (socket) => socketConnections.push(socket.url()))
  await page.addInitScript(() => localStorage.setItem('kurio-scenario', 'socket-disconnect-once'))
  await page.goto('/')
  await expect.poll(() => socketConnections.length, { timeout: 15_000 }).toBeGreaterThan(1)
  expect(socketConnections.some((url) => url.includes('/socket.io'))).toBeTruthy()
  await expect(page.getByText('Emerald Ape #042', { exact: true })).toBeVisible()
})

