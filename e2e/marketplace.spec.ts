test('new collector can register, update profile and authenticate with a changed password', async ({ page }) => {
  const email = `e2e-${test.info().project.name}@kurio.test`
  await page.goto('/cadastro')
  await page.getByLabel('Nome').fill('Colecionador E2E')
  await page.getByLabel('E-mail').fill(email)
  await page.getByLabel('Senha', { exact: true }).fill('kurio123')
  await page.getByLabel('Confirmar senha').fill('kurio123')
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click()
  await expect(page).toHaveURL(/\/perfil$/)
  await expect(page.getByRole('heading', { name: 'Perfil do colecionador' })).toBeVisible()

  await page.getByLabel(/Nome de exibição/).fill('Colecionador Atualizado')
  await page.getByLabel(/Nome de usuário/).fill('colecionador_e2e')
  await page.getByLabel('E-mail').fill(email)
  await page.getByRole('textbox', { name: /Nome ENS/ }).fill('colecionadore2e')
  await page.getByLabel(/Apelido da carteira/).fill('Carteira E2E')
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Perfil atualizado.')
  await page.getByLabel('Senha atual').fill('kurio123')
  await page.locator('input[name="newPassword"]').fill('kurio456')
  await page.locator('input[name="confirmPassword"]').fill('kurio456')
  await expect(page.locator('input[name="currentPassword"]')).toHaveValue('kurio123')
  await expect(page.locator('input[name="newPassword"]')).toHaveValue('kurio456')
  const passwordResponse = page.waitForResponse((response) => response.url().endsWith('/api/profile/password'))
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  expect((await passwordResponse).status()).toBe(200)
  await expect(page.getByRole('status')).toContainText('Senha alterada com sucesso.')

  await page.getByRole('button', { name: 'Sair' }).click()
  await page.goto('/login')
  await page.getByLabel('E-mail').fill(email)
  await page.getByLabel('Senha').fill('kurio456')
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page).toHaveURL(/\/perfil$/)
  await expect(page.getByLabel(/Nome de exibição/)).toHaveValue('Colecionador Atualizado')
  await expect(page.getByLabel(/Nome de usuário/)).toHaveValue('colecionador_e2e')
  await expect(page.getByRole('textbox', { name: /Nome ENS/ })).toHaveValue('colecionadore2e')
  await expect(page.getByLabel(/Apelido da carteira/)).toHaveValue('Carteira E2E')
})

